"""Generate src/continua_table.rs: every code point that t2b_scorer.to_continua keeps, and the letter it becomes.

to_continua is per-character (NFD, drop U+0300-U+036F, upper, Ϲ/C/ς -> Σ, keep Α-Ω), checked here on random
strings, so a code point table reproduces it exactly.

  python -I -X utf8 t2b-wasm/tools/gen_continua.py
"""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "galen-density-map" / "pipeline"))
import t2b_scorer as T  # noqa: E402

# U+03A2 is unassigned but inside the Α-Ω range that to_continua keeps; it becomes code 24, a "letter" no form
# contains (it can only be read as part of an unknown segment)
LETTERS = T.LETTERS + "΢"
table = {}
for cp in range(0x110000):
    if 0xD800 <= cp < 0xE000:
        continue
    r = T.to_continua(chr(cp))
    if r:
        assert len(r) == 1 and r in LETTERS, (hex(cp), r)
        table[cp] = LETTERS.index(r)
rng = random.Random(1)
pool = list(table) + [0x20, 0x301, 0x313, 0x345, 0x342, 0x2E, 0x1FBD, 0x5B, 0x5D, 0x0A]
for _ in range(50000):
    s = "".join(chr(rng.choice(pool)) for _ in range(rng.randint(1, 10)))
    assert T.to_continua(s) == "".join(LETTERS[table[ord(c)]] for c in s if ord(c) in table), s
rows = ",\n".join(f"    (0x{cp:05X}, {code})" for cp, code in sorted(table.items()))
out = HERE.parent / "src" / "continua_table.rs"
out.write_text("// Generated by tools/gen_continua.py from t2b_scorer.to_continua; do not edit.\n"
               "// (code point, letter code 0..23 in ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩ order, 24 = U+03A2), sorted by code point.\n"
               f"pub static CONTINUA: [(u32, u8); {len(table)}] = [\n{rows},\n];\n", encoding="utf-8")
print(f"{len(table)} code points -> {out}")
